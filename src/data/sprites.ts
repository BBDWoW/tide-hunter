const sin = Math.sin;

function star(s: Painter, cx: number, cy: number, ro: number, ri: number) {
  const pts: [number, number][] = [];
  for (let k = 0; k < 10; k++) {
    const a = -Math.PI / 2 + (k * Math.PI) / 5, r = k % 2 ? ri : ro;
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  for (let k = 0; k < 10; k++) {
    const [ax, ay] = pts[k], [bx, by] = pts[(k + 1) % 10];
    s.t(cx, cy, ax, ay, bx, by, 'm');
  }
}

